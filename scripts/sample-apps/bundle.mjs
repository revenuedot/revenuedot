// Bundles the sample apps the dashboard offers under "Test your setup with the sample app" from the revenuedot/examples
// repo into the server (apps/server/src/services/sample-apps/examples.generated.ts), so the zip is built on any
// deployment without network access. Rerun after the examples change:
//   node scripts/sample-apps/bundle.mjs [path to a revenuedot/examples checkout, default ../examples]
import { execFileSync } from "node:child_process";
import { readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const examples = resolve(process.argv[2] ?? join(root, "../examples"));
/** Example folder in revenuedot/examples for each sample platform (services/sample-apps/index.ts). */
const DIRS = { ios: "mobile/ios-swiftui", android: "mobile/android-compose", flutter: "mobile/flutter", react_native: "mobile/react-native-expo", web: "web/purchases-js-vite" };
// Test suites and build output are not part of a sample someone opens in Xcode or Android Studio.
const SKIP = [/(^|\/)e2e\//, /(^|\/)playwright\.config\.ts$/, /(^|\/)dist\//];

const git = (...a) => execFileSync("git", ["-C", examples, ...a], { encoding: "utf8", maxBuffer: 64 << 20 });
if (git("status", "--porcelain").trim()) console.warn("warning: the examples checkout has uncommitted changes; only committed files are bundled");
const commit = git("rev-parse", "HEAD").trim();
const out = {};
let bytes = 0;
for (const [platform, dir] of Object.entries(DIRS)) {
  const files = git("ls-files", "-z", dir).split("\0").filter(Boolean).filter((f) => !SKIP.some((r) => r.test(f.slice(dir.length + 1))));
  out[platform] = { dir, files: files.map((f) => {
    const blob = execFileSync("git", ["-C", examples, "show", `HEAD:${f}`], { maxBuffer: 64 << 20 });
    bytes += blob.length;
    const text = !blob.includes(0) && Buffer.from(blob.toString("utf8"), "utf8").equals(blob);
    const mode = (statSync(join(examples, f)).mode & 0o111) ? 0o755 : 0o644;
    return [f.slice(dir.length + 1), mode, text ? "t" : "b", text ? blob.toString("utf8") : blob.toString("base64")];
  }) };
}
const target = join(root, "apps/server/src/services/sample-apps/examples.generated.ts");
writeFileSync(target, `// Generated by scripts/sample-apps/bundle.mjs from https://github.com/revenuedot/examples/tree/${commit}. Do not edit.\n`
  + `export const EXAMPLES_COMMIT = ${JSON.stringify(commit)};\n`
  + `/** Per platform: the example's folder and its files as [path, mode, "t" text | "b" base64, data]. */\n`
  + `export const EXAMPLES: Record<string, { dir: string; files: Array<[string, number, "t" | "b", string]> }> = ${JSON.stringify(out)};\n`);
console.log(`bundled ${Object.values(out).reduce((n, x) => n + x.files.length, 0)} files (${(bytes / 1024).toFixed(0)} KB) from examples@${commit.slice(0, 7)} into ${target}`);

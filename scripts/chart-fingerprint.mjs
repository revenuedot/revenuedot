// RevenueDot: open-source, self-hostable alternative to RevenueCat. Same SDK API, free.
// This file: writes packages/core/src/charts/fingerprint.generated.ts, a hash of the source files that compute chart
// numbers. Stored daily rollups made by other code are rebuilt (prd/charts/PRD.md "Daily rollups").
// Run: node scripts/chart-fingerprint.mjs (packages/core/test/chart-rollups.test.ts fails when it is stale).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

export const CHART_SOURCES = [
  "packages/core/src/charts/compute.ts", "packages/core/src/charts/model.ts", "packages/core/src/charts/periods.ts",
  "packages/core/src/charts/time.ts", "packages/core/src/charts/catalog.ts", "packages/core/src/charts/rollup.ts",
  "packages/core/src/tax.ts", "packages/core/src/commission.ts", "packages/core/src/events.ts",
  "packages/core/src/charts/run.ts",
  "apps/server/src/services/charts/load.ts", "apps/server/src/services/charts/rollups.ts", "apps/server/src/services/commission.ts", "apps/server/src/services/fx.ts",
];
const root = new URL("..", import.meta.url);
export function chartFingerprint() {
  const h = createHash("sha256");
  for (const f of CHART_SOURCES) h.update(f).update("\0").update(readFileSync(new URL(f, root)).toString().replace(/\r\n/g, "\n")).update("\0");
  return h.digest("hex").slice(0, 16);
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const out = new URL("packages/core/src/charts/fingerprint.generated.ts", root);
  writeFileSync(out, `// Generated by scripts/chart-fingerprint.mjs from the files that compute chart numbers. Do not edit by hand.\nexport const CHART_CODE_FINGERPRINT = "${chartFingerprint()}";\n`);
  console.log("chart fingerprint", chartFingerprint());
}

// Rebuilds src/data/evidence.ts from evidence-pages.mjs and the capture log written by capture-evidence.mjs.
//   node apps/site/scripts/gen-evidence.mjs [--date YYYY-MM-DD]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { PAGES } from "./evidence-pages.mjs";

const here = path.dirname(new URL(import.meta.url).pathname);
const SITE = path.resolve(here, "..");
const SCRATCH = process.env.EVIDENCE_SCRATCH ?? path.join(SITE, ".evidence-scratch");
const args = process.argv.slice(2);
const DATE = args.includes("--date") ? args[args.indexOf("--date") + 1] : "2026-10-04";
const log = JSON.parse(readFileSync(path.join(SCRATCH, "capture-log.json"), "utf8"));
const NAMES = { revenuecat: "RevenueCat", adapty: "Adapty", qonversion: "Qonversion", superwall: "Superwall", apphud: "Apphud", stripe: "Stripe", apple: "Apple", google: "Google", purchasely: "Purchasely", iaphub: "IAPHUB", nami: "Nami ML", revenuedot: "RevenueDot" };
const PAGE_LABEL = { home: "homepage", pricing: "pricing page", "security-and-compliance": "security and compliance page", gdpr: "GDPR page" };
const label = (vendor, page, url) => {
  if (PAGE_LABEL[page]) return `${NAMES[vendor]} ${PAGE_LABEL[page]}`;
  if (page.startsWith("github-")) return `${NAMES[vendor]} GitHub page`;
  if (page.startsWith("docs") || page.includes("llms")) return `${NAMES[vendor]} docs page`;
  if (page.startsWith("blog")) return `${NAMES[vendor]} blog post`;
  if (page.startsWith("community")) return `${NAMES[vendor]} community thread`;
  return `${NAMES[vendor]} page ${new URL(url).pathname}`;
};
const q = (s) => JSON.stringify(s);

const out = [];
out.push(`// Evidence pack: dated screenshots of every vendor page cited in compare.ts and alternatives.ts, captured ${DATE} with headless
// Chromium at 1280x800 (full pages at 1x, crops at 2x, light colour scheme, cookie banners declined or hidden). Generated by
// scripts/gen-evidence.mjs from scripts/evidence-pages.mjs after scripts/capture-evidence.mjs; do not edit by hand.
// Each crop proves one claim the comparison pages make; "alt" describes what is visible.`);
out.push(`export type EvidenceCrop = {
  /** Short claim slug, e.g. "free-to-2500-then-1-percent". */
  claim: string;
  /** Asset path relative to this file, resolvable with import.meta.glob("../assets/evidence/**"). */
  file: string;
  /** What the crop shows, for the img alt text. */
  alt: string;
  /** "<Vendor> <page>, captured <date>: <the one claim it shows>." */
  caption: string;
};

export type Evidence = {
  vendor: string;
  /** Page slug, e.g. "pricing" or "docs-web-overview". */
  page: string;
  url: string;
  /** Capture date, ISO. */
  captured: string;
  /** Full-page screenshot (the first segment when the page was split; see fullParts). */
  full: string;
  /** All full-page segments in reading order, when the page was taller than 4,000 CSS px. */
  fullParts?: string[];
  crops: EvidenceCrop[];
};

const DATE = ${q(DATE)};
const asset = (vendor: string, file: string) => \`../assets/evidence/\${vendor}/\${file}\`;
`);
out.push(`export const EVIDENCE: Evidence[] = [`);
let vendorPrev = "";
let nCrops = 0;
const summary = {};
for (const p of PAGES) {
  const e = log.find((x) => x.vendor === p.vendor && x.page === p.page);
  if (!e || !e.ok || !e.full.length) { console.error("MISSING", p.vendor, p.page); continue; }
  const crops = e.crops.filter((c) => c.file && existsSync(path.join(SITE, "src/assets/evidence", p.vendor, c.file)));
  if (p.vendor !== vendorPrev) { out.push(`  // ---- ${NAMES[p.vendor]} ----`); vendorPrev = p.vendor; }
  const pageLabel = label(p.vendor, p.page, p.url);
  out.push(`  {`);
  out.push(`    vendor: ${q(NAMES[p.vendor])},`);
  out.push(`    page: ${q(p.page)},`);
  out.push(`    url: ${q(p.url)},`);
  out.push(`    captured: DATE,`);
  out.push(`    full: asset(${q(p.vendor)}, ${q(e.full[0])}),`);
  if (e.full.length > 1) out.push(`    fullParts: [${e.full.map((f) => `asset(${q(p.vendor)}, ${q(f)})`).join(", ")}],`);
  out.push(`    crops: [`);
  for (const c of crops) {
    const cfg = p.crops.find((x) => x.claim === c.claim);
    out.push(`      {`);
    out.push(`        claim: ${q(c.claim)},`);
    out.push(`        file: asset(${q(p.vendor)}, ${q(c.file)}),`);
    out.push(`        alt: ${q(cfg.alt)},`);
    out.push(`        caption: ${q(`${pageLabel}, captured ${DATE}: ${cfg.caption}.`)},`);
    out.push(`      },`);
    nCrops++;
  }
  out.push(`    ],`);
  out.push(`  },`);
  (summary[p.vendor] ??= []).push(`${p.page} (${crops.length})`);
}
out.push(`];`);
out.push(``);
out.push(`/** Evidence for one vendor page, e.g. evidenceFor("RevenueCat", "pricing"). */
export const evidenceFor = (vendor: string, page: string): Evidence | undefined => EVIDENCE.find((e) => e.vendor === vendor && e.page === page);
`);
writeFileSync(path.join(SITE, "src/data/evidence.ts"), out.join("\n"));
console.log("crops:", nCrops);
for (const [v, pages] of Object.entries(summary)) console.log(NAMES[v] + ": " + pages.join(", "));
